// Model cards take their name, vendor, price and provenance from the registry, so
// a lineup change in data/models.ts flows through here; only the judgement lives below.
function fromModel(id: string): Pick<Tool, "name" | "creator" | "pricing" | "sources" | "lastVerified"> {
  const entry = model(id);
  return {
    name: entry.name,
    creator: entry.vendor,
    pricing: entry.pricingNote ?? "See the vendor's pricing page",
    sources: entry.sources,
    lastVerified: entry.lastVerified,
  };
}

